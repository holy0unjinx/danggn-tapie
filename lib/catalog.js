function hash(value) {
  let total = 0;
  for (const character of String(value)) total = (total * 33 + character.charCodeAt(0)) >>> 0;
  return total;
}

export function decodeHtml(value) {
  return String(value || '')
    .replaceAll('&amp;', '&')
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&nbsp;', ' ');
}

export function fullRegion(region) {
  const name = String(region || '').trim();
  if (!name) return '경기 수원시 장안구 정자동';
  return REGION_PREFIX[name] || `경기 수원시 장안구 ${name}`;
}

export function inferCategory(title) {
  const text = decodeHtml(title);
  if (/노트북|갤럭시|아이폰|ssd|플레이스테이션|킥보드|드라이기|제습|사운드바|송풍기|컨트롤러/i.test(text)) return '디지털기기';
  if (/책상|액자|수납|서랍|크리스마스|트리|워터글로브|멜로디/i.test(text)) return '가구/인테리어';
  if (/청바지|나시|블라우스|후드|니트|원피스|반팔|바람막이|패딩|플리스|폴로|크록스|셋업|트레이닝|조끼/i.test(text)) return '의류';
  if (/골프|복싱|아이스박스|드라이버|퍼터|글러브/i.test(text)) return '스포츠/레저';
  if (/도서|책/i.test(text)) return '도서';
  if (/바디드라이|영양제|다리미|보관증|교환권/i.test(text)) return '생활/주방';
  if (/시계|에코백|파우치|가방|동전|포켓몬/i.test(text)) return '기타';
  return '기타';
}

export function avatarImage(name, id) {
  const seed = hash(id || name);
  const fill = COLORS[seed % COLORS.length];
  const initial = String(name || '이').slice(0, 1);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="32" fill="${fill}"/><text x="32" y="42" text-anchor="middle" fill="#fff" font-size="28" font-family="system-ui,sans-serif" font-weight="700">${initial}</text></svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

export function makeSeller(article, overrides = {}) {
  const seed = hash(article.id);
  const name = overrides.name || NAMES[seed % NAMES.length];
  const region = overrides.region || fullRegion(article.region);
  return {
    name,
    region,
    temperature: overrides.temperature || `${(36.2 + (seed % 171) / 10).toFixed(1)}°C`,
    image: overrides.image || avatarImage(name, article.id),
  };
}

export function presentDescription(article) {
  const written = String(article.description || '').trim();
  if (written && written !== '저장된 검색 결과에서 가져온 상품입니다.') return written;
  if (DESCRIPTIONS[article.id]) return DESCRIPTIONS[article.id];
  const title = decodeHtml(article.title);
  const region = article.region || '정자동';
  if (article.price === '나눔') {
    return `${title} 나눔합니다.\n자리 없어서 정리해요. ${region}에서 직접 가져가실 수 있는 분으로 부탁드려요.`;
  }
    return `${title} 판매합니다.\n사용감 있는 중고이고, 사진은 직접 찍은 실물입니다. ${region}에서 직거래 가능해요.\n가격은 ${article.price}입니다. 관심 있으시면 채팅 주세요.`;
}

export function presentSeller(article) {
  const seller = article.seller;
  if (seller?.name) {
    return makeSeller(article, {
      name: seller.name,
      region: seller.region || fullRegion(article.region),
      temperature: seller.temperature,
      image: seller.image,
    });
  }
  return makeSeller(article);
}
